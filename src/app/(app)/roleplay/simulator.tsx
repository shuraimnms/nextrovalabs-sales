"use client";
import { useRef, useState, useTransition } from "react";
import { Bot, Cpu, Send } from "lucide-react";
import { roleplayFinishAction, roleplayStartAction, roleplayTurnAction } from "@/app/actions-content";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Select, Textarea } from "@/components/ui/input";
import { ProgressBar } from "@/components/ui/progress";
import { CRITERIA, MAX_USER_TURNS, type Scores, type Turn } from "@/lib/roleplay/engine";
import { DIFFICULTY } from "@/lib/labels";
import { cn } from "@/lib/utils/cn";

type Opt = { key: string; label: string; blurb?: string };
type Past = { id: string; personality: string; project: string; difficulty: string; mode: string; overall: number; at: string };

export function Simulator({ aiEnabled, personalities, projects, history }: { aiEnabled: boolean; personalities: Opt[]; projects: Opt[]; history: Past[] }) {
  const [personality, setPersonality] = useState(personalities[0].key);
  const [project, setProject] = useState(projects[0].key);
  const [level, setLevel] = useState("BEGINNER");
  const [turns, setTurns] = useState<Turn[] | null>(null);
  const [mode, setMode] = useState<"RULE_BASED" | "AI">(aiEnabled ? "AI" : "RULE_BASED");
  const [fellBack, setFellBack] = useState(false);
  const [draft, setDraft] = useState("");
  const [result, setResult] = useState<{ scores: Scores; feedback: string[] } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, start] = useTransition();
  const endRef = useRef<HTMLDivElement>(null);
  const userCount = turns?.filter((t) => t.role === "user").length ?? 0;

  const base = () => ({ personality, project, level });
  function begin() {
    setError(null); setResult(null); setFellBack(false);
    start(async () => {
      const r = await roleplayStartAction(base());
      if (!r.ok) return setError(r.error);
      setMode(r.aiAvailable ? "AI" : "RULE_BASED");
      setTurns([{ role: "customer", text: r.opening }]);
    });
  }
  function send() {
    if (!turns || !draft.trim() || pending) return;
    const next: Turn[] = [...turns, { role: "user", text: draft.trim() }];
    setTurns(next); setDraft(""); setError(null);
    start(async () => {
      const r = await roleplayTurnAction({ ...base(), history: next });
      if (!r.ok) return setError(r.error);
      if (r.fellBack) setFellBack(true);
      setMode(r.mode);
      const withReply = [...next, { role: "customer" as const, text: r.text }];
      setTurns(withReply);
      setTimeout(() => endRef.current?.scrollIntoView({ behavior: "smooth", block: "nearest" }), 50);
      if (r.ended) finish(withReply, r.mode);
    });
  }
  function finish(h: Turn[] | null = turns, m = mode) {
    if (!h) return;
    start(async () => {
      const r = await roleplayFinishAction({ ...base(), history: h, mode: m });
      if (!r.ok) return setError(r.error);
      setResult({ scores: r.scores, feedback: r.feedback });
    });
  }

  if (!turns) {
    return (
      <div className="space-y-6">
        <div className="rounded-xl border border-border bg-card p-5">
          <div className="mb-4 flex items-center gap-2 text-sm">
            {aiEnabled ? <Badge tone="success"><Bot className="size-3" aria-hidden />AI customer enabled</Badge> : <Badge tone="warning"><Cpu className="size-3" aria-hidden />Rule-based practice mode</Badge>}
            <span className="text-muted-foreground">{aiEnabled ? "Replies are generated by an AI model on the server." : "Replies are scripted and scores are heuristic checks — not AI. An admin can enable an AI provider."}</span>
          </div>
          <div className="grid gap-4 sm:grid-cols-3">
            <label className="text-sm font-medium">Customer type<Select value={personality} onChange={(e) => setPersonality(e.target.value)} className="mt-1">{personalities.map((p) => <option key={p.key} value={p.key}>{p.label}</option>)}</Select><span className="mt-1 block text-xs text-muted-foreground">{personalities.find((p) => p.key === personality)?.blurb}</span></label>
            <label className="text-sm font-medium">Project<Select value={project} onChange={(e) => setProject(e.target.value)} className="mt-1">{projects.map((p) => <option key={p.key} value={p.key}>{p.label}</option>)}</Select></label>
            <label className="text-sm font-medium">Difficulty<Select value={level} onChange={(e) => setLevel(e.target.value)} className="mt-1">{Object.entries(DIFFICULTY).map(([k, v]) => <option key={k} value={k}>{v}</option>)}</Select></label>
          </div>
          {error && <p role="alert" className="mt-3 text-sm text-danger">{error}</p>}
          <Button className="mt-5" onClick={begin} disabled={pending}>Start roleplay</Button>
        </div>
        <section aria-labelledby="past"><h2 id="past" className="mb-3 text-lg font-semibold">Your recent sessions</h2>
          {history.length === 0 ? <p className="text-sm text-muted-foreground">No sessions yet. Your scores will appear here.</p> : (
            <ul className="divide-y divide-border rounded-xl border border-border bg-card">{history.map((h) => <li key={h.id} className="flex flex-wrap items-center justify-between gap-2 p-3 text-sm"><span><strong>{h.personality}</strong> · {h.project} · {DIFFICULTY[h.difficulty]}</span><span className="flex items-center gap-2"><Badge>{h.mode === "AI" ? "AI" : "Rule-based"}</Badge><strong>{h.overall}/100</strong><time className="text-xs text-muted-foreground" dateTime={h.at}>{new Date(h.at).toLocaleDateString("en-IN")}</time></span></li>)}</ul>)}
        </section>
      </div>
    );
  }

  if (result) {
    return (
      <div className="space-y-5">
        <div className="rounded-xl bg-accent p-5 text-accent-foreground"><p className="text-sm">Overall score ({mode === "AI" ? "AI conversation, heuristic scoring" : "rule-based practice, heuristic scoring"})</p><p className="text-4xl font-semibold">{result.scores.overall}/100</p></div>
        <ul className="grid gap-3 sm:grid-cols-2">{CRITERIA.map((c) => <li key={c.key} className="rounded-xl border border-border bg-card p-4"><ProgressBar value={result.scores[c.key]} label={`${c.label}: ${result.scores[c.key]} out of 100`} /><p className="mt-2 flex justify-between text-sm"><span className="font-medium">{c.label}</span><span>{result.scores[c.key]}</span></p></li>)}</ul>
        <div className="rounded-xl border border-border bg-card p-5"><h2 className="font-semibold">Feedback</h2><ul className="mt-2 list-disc space-y-1 pl-5 text-sm">{result.feedback.map((f) => <li key={f}>{f}</li>)}</ul></div>
        <p className="text-xs text-muted-foreground">Scores come from simple checks on tone, questions, acknowledgements, honesty and next steps. They guide practice; they are not an assessment of real performance.</p>
        <Button onClick={() => { setTurns(null); setResult(null); }}>Practise again</Button>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2 text-sm">
        <span className="flex items-center gap-2">{mode === "AI" ? <Badge tone="success"><Bot className="size-3" aria-hidden />AI customer</Badge> : <Badge tone="warning"><Cpu className="size-3" aria-hidden />Rule-based mode</Badge>}{fellBack && <span className="text-warning">AI unavailable — switched to rule-based replies.</span>}</span>
        <span className="text-muted-foreground">Turn {Math.min(userCount + 1, MAX_USER_TURNS)} of {MAX_USER_TURNS}</span>
      </div>
      <ol aria-label="Conversation" aria-live="polite" className="max-h-[55vh] space-y-3 overflow-y-auto rounded-xl border border-border bg-card p-4">
        {turns.map((t, i) => <li key={i} className={cn("max-w-[85%] rounded-2xl px-4 py-2.5 text-sm", t.role === "user" ? "ml-auto bg-primary text-primary-foreground" : "bg-muted")}><span className="sr-only">{t.role === "user" ? "You: " : "Customer: "}</span>{t.text}</li>)}
        {pending && <li className="text-sm text-muted-foreground" role="status">Customer is replying…</li>}
        <div ref={endRef} />
      </ol>
      {error && <p role="alert" className="text-sm text-danger">{error}</p>}
      <form onSubmit={(e) => { e.preventDefault(); send(); }} className="flex gap-2">
        <Textarea value={draft} onChange={(e) => setDraft(e.target.value)} onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); send(); } }} rows={2} maxLength={800} aria-label="Your reply" placeholder="Type your reply in Hinglish… (Enter to send)" disabled={pending} />
        <Button type="submit" disabled={pending || !draft.trim()} aria-label="Send reply"><Send /></Button>
      </form>
      <div className="flex gap-2"><Button variant="outline" onClick={() => finish()} disabled={pending || userCount === 0}>Finish and get feedback</Button><Button variant="ghost" onClick={() => setTurns(null)}>Cancel</Button></div>
      <p className="text-xs text-muted-foreground">Do not type real customer names, phone numbers or details. Only scores are saved.</p>
    </div>
  );
}
